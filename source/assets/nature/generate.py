#!/usr/bin/env python3
"""Emit C audio data from the nine editable, block-framed 16 kHz mono assets."""
import argparse
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parent
target = root.parents[1] / "app/dsp/nature_bank.inc"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
rows = json.loads((root / "manifest.json").read_text())
if len(rows) != 9:
    raise SystemExit("Expected Water, Rain and seven bird calls")
out = ["/* Generated by assets/nature/generate.py */"]
descriptors = []
for index, row in enumerate(rows):
    data = (root / (row["name"] + ".adpcm")).read_bytes()
    frames = row["frames"]
    if not (0 < frames and ((frames + 1023) // 1024) * 516 == len(data) == row["bytes"]):
        raise SystemExit("Invalid lengths for " + row["name"])
    if hashlib.sha256(data).hexdigest() != row["sha256"]:
        raise SystemExit("Asset digest mismatch for " + row["name"])
    out.append(f"static const uint8_t nature_data_{index}[] = {{")
    for i in range(0, len(data), 24):
        out.append("    " + ", ".join(f"0x{x:02x}" for x in data[i:i+24]) + ",")
    out.append("};")
    descriptors.append(f"    {{ nature_data_{index}, {frames}u }}, /* {row['name']} */")
out += ["static const NatureAsset nature_bank[] = {", *descriptors, "};", ""]
content = "\n".join(out).encode("ascii")
if args.check:
    if not target.is_file() or target.read_bytes() != content:
        raise SystemExit("Regenerate app/dsp/nature_bank.inc")
else:
    target.write_bytes(content)
