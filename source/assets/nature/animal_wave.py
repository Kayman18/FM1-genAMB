#!/usr/bin/env python3
"""Build the genAMB external animal bank from the full recordings."""
import argparse
import array
import binascii
import hashlib
import json
import math
from pathlib import Path
import statistics
import struct
import subprocess
import sys
import zlib
from encode import block
from normalize_rain import measure

ROOT = Path(__file__).resolve().parent
RECORDINGS = [('Finch 1', '043_G2_V1_Finch1.wav'), ('Finch 2', '044_G#2_V1_Finch2.wav'),
              ('Squirrel 3', '054_F#3_V1_Squirrel3.wav')]
OFFSET = 0x97000
LIMIT = 0xDC000
HEADER = 64

def prepare(name, target):
    f = ROOT/'recordings'/name
    raw = subprocess.check_output(['ffmpeg','-v','error','-i',str(f),'-ac','1','-ar','16000','-f','f64le','-'])
    samples = array.array('d',raw)
    if sys.byteorder != 'little': samples.byteswap()
    mean = sum(samples)/len(samples)
    for i in range(len(samples)):
        samples[i] = (samples[i]-mean) * min(i/159, (len(samples)-1-i)/159, 1.0)
    rms = math.sqrt(sum(v*v for v in samples)/len(samples))
    gain = min(10**(target/20)/rms, 0.88/max(map(abs,samples)))
    pcm = array.array('h',(round(v*gain*32767) for v in samples))
    data = b''.join(block(pcm[i:i+1024]) for i in range(0,len(pcm),1024))
    rms_db, peak_db = measure(data,len(pcm))
    return data, dict(recording=name, frames=len(pcm), bytes=len(data), decoded_rms_dbfs=round(rms_db,3),
                      decoded_peak_dbfs=round(peak_db,3), sha256=hashlib.sha256(data).hexdigest(),
                      recording_sha256=hashlib.sha256(f.read_bytes()).hexdigest())

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    old=json.loads((ROOT/'manifest.json').read_text())
    target=statistics.median(measure((ROOT/(r['name']+'.adpcm')).read_bytes(),r['frames'])[0] for r in old[2:])
    rows=[]
    payload=bytearray()
    entries=b''
    for label,name in RECORDINGS:
        data,row=prepare(name,target)
        row.update(name=label, offset=HEADER+len(payload))
        entries+=struct.pack('<III',row['offset'],row['frames'],row['bytes'])
        payload+=data
        rows.append(row)
    data_crc=zlib.crc32(payload)
    length=HEADER+len(payload)
    h=struct.pack('<8s4I',b'GNANIM02',1,len(rows),length,data_crc)+entries
    assert len(h)==60
    head_crc=zlib.crc32(h)
    image=h+struct.pack('<I',head_crc)+payload
    image+=b'\xff'*(-len(image)%4096)
    assert OFFSET+len(image)<=LIMIT
    header=f'''/* Generated by assets/nature/animal_wave.py. */
#pragma once
#define ANIMAL_WAVE_BASE 0x{OFFSET:x}u
#define ANIMAL_WAVE_END 0x{OFFSET+len(image):x}u
#define ANIMAL_WAVE_COUNT {len(rows)}u
#define ANIMAL_WAVE_HEADER {HEADER}u
#define ANIMAL_WAVE_LENGTH {length}u
#define ANIMAL_WAVE_HEAD_CRC 0x{head_crc:08x}u
#define ANIMAL_WAVE_DATA_CRC 0x{data_crc:08x}u
#define ANIMAL_WAVE_IMAGE_CRC16 0x{binascii.crc_hqx(image,0):04x}u
'''
    files={ROOT/'animal-wave.bin':image, ROOT/'animal-wave.json':(json.dumps(rows,indent=2)+'\n').encode(),
           ROOT.parents[1]/'app/dsp/animal_wave_layout.h':header.encode()}
    for f,content in files.items():
        if args.check:
            if f.read_bytes()!=content: raise SystemExit('Regenerate '+f.name)
        else: f.write_bytes(content)
    for row in rows: print(row['name'],row['frames'],row['bytes'],row['decoded_peak_dbfs'])
    print('Payload',len(payload),'bank',length,'sector allocation',len(image))
if __name__=='__main__':main()
